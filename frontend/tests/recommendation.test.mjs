import assert from 'node:assert/strict';
import {ITEMS,CATEGORIES,NOTICE_CATEGORIES,PROGRAM_CATEGORIES,matchProfile,statusOf,daysLeft,sourceUrl,todayDate} from '../dist/data.js';
import {TRACK_COLLEGES,TRACK_OPTIONS,trackOptionsForSlot,normalizeTrackSearch,isSelectableTrack} from '../dist/tracks.js';
const fourth={grade:4,tracks:['기업경영트랙','글로벌비즈니스트랙'],interests:['career','intern','contest']};
const first={grade:1,tracks:['IT공과대학'],interests:['study','wellbeing']};
assert.equal(ITEMS.length,18);assert.equal(new Set(ITEMS.map(i=>i.id)).size,18);
assert(ITEMS.every(i=>CATEGORIES.some(c=>c.id===i.category)));
assert(ITEMS.filter(i=>i.type==='program').every(i=>PROGRAM_CATEGORIES.some(c=>c.id===i.programCategory)));
assert(matchProfile(ITEMS.find(i=>i.id==='n03'),fourth).eligible);
assert(!matchProfile(ITEMS.find(i=>i.id==='n12'),fourth).eligible);
assert(!matchProfile(ITEMS.find(i=>i.id==='p02'),first).eligible);
assert(matchProfile(ITEMS.find(i=>i.id==='p11'),first).eligible);
assert.equal(statusOf(ITEMS.find(i=>i.id==='p13'),'2026-10-09'),'open');
assert.equal(daysLeft(ITEMS.find(i=>i.id==='p13'),'2026-10-09'),0);
assert.equal(statusOf(ITEMS.find(i=>i.id==='p15'),'2026-10-09'),'closed');
assert.equal(statusOf(ITEMS.find(i=>i.id==='n14'),'2026-10-09'),'upcoming');
assert.equal(todayDate(new Date('2026-10-10T14:59:59Z')),'2026-10-10');
assert.equal(todayDate(new Date('2026-10-10T15:00:00Z')),'2026-10-11');
assert.equal(todayDate(new Date('2026-10-11T14:59:59Z')),'2026-10-11');
assert.equal(daysLeft(ITEMS.find(i=>i.id==='n01'),'2026-10-11'),5);
assert.equal(daysLeft(ITEMS.find(i=>i.id==='p05'),'2026-10-11'),0);
assert.equal(statusOf(ITEMS.find(i=>i.id==='p05'),'2026-10-11'),'open');
assert.equal(statusOf(ITEMS.find(i=>i.id==='p05'),'2026-10-12'),'closed');
assert.equal(daysLeft(ITEMS.find(i=>i.id==='p13'),'2026-10-11'),-2);
assert.equal(statusOf(ITEMS.find(i=>i.id==='p13'),'2026-10-11'),'closed');
assert.equal(statusOf(ITEMS.find(i=>i.id==='n14'),'2026-10-15'),'open');
assert.equal(daysLeft({deadline:'2027-01-01'},'2026-12-31'),1);
assert.equal(daysLeft({deadline:'2028-03-01'},'2028-02-28'),2);
assert.equal(daysLeft(ITEMS[0]),daysLeft(ITEMS[0],todayDate()));
assert(ITEMS.find(i=>i.id==='p16').benefit===null);
assert(sourceUrl('notice').startsWith('https://www.hansung.ac.kr/'));
assert(sourceUrl('program').startsWith('https://hsportal.hansung.ac.kr/'));
assert.equal(TRACK_COLLEGES.length,8);
assert.deepEqual(TRACK_COLLEGES.map(c=>c.groups.flatMap(g=>g.entries).length),[12,11,11,10,7,7,10,5]);
assert.equal(TRACK_OPTIONS.length,73);
assert.equal(new Set(TRACK_OPTIONS.map(t=>t.id)).size,73);
assert.equal(new Set(TRACK_OPTIONS.map(t=>t.name)).size,73);
assert.equal(normalizeTrackSearch('UX / UI 디자인'),normalizeTrackSearch('ux/ui디자인'));
assert(TRACK_OPTIONS.some(t=>t.searchText.includes('지능형실감미디어공학트랙')));
assert(TRACK_OPTIONS.some(t=>t.name==='자율교양학부'));
assert(!isSelectableTrack('미정')&&isSelectableTrack('웹공학트랙')&&!isSelectableTrack('없는 트랙'));
assert(ITEMS.filter(i=>i.type==='notice').every(i=>NOTICE_CATEGORIES.some(c=>c.id===i.noticeCategory)));
assert.deepEqual(NOTICE_CATEGORIES.map(c=>c.name),['학사','장학·지원','진로·취업','현장실습','비교과','창업','국제·교류']);
assert(isSelectableTrack('IT공과대학',{slot:1,grade:1}));
assert(!isSelectableTrack('IT공과대학',{slot:2,grade:1}));
assert(isSelectableTrack('컴퓨터공학부',{slot:1,grade:1}));
assert(isSelectableTrack('컴퓨터공학부',{slot:2,grade:2}));
assert(!isSelectableTrack('웹공학트랙',{slot:1,grade:1}));
assert(isSelectableTrack('웹공학트랙',{slot:1,grade:2}));
for(const slot of [1,2,3])assert(!isSelectableTrack('미정',{slot,grade:1}));
assert(trackOptionsForSlot({slot:1,grade:1}).every(t=>t.kind==='college'||t.kind==='department'));
const other={grade:'other',tracks:['미정'],interests:['study']};
assert(ITEMS.filter(i=>matchProfile(i,other).eligible).every(i=>i.grades.length===4));
assert(!matchProfile(ITEMS.find(i=>i.id==='p11'),other).eligible);
const third={grade:4,tracks:['미정','글로벌비즈니스트랙','웹공학트랙'],interests:['intern']};
const web=ITEMS.find(i=>i.tracks.includes('웹공학'));
assert(web&&matchProfile(web,third).eligible);
assert(!matchProfile(web,{...third,tracks:third.tracks.slice(0,2)}).eligible);
console.log('PASS: dataset, program taxonomy and recommendation checks');
